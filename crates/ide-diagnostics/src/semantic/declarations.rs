//! Declaration and type well-formedness rules that do not require body inference.
//! Work on live CST definitions so disabled preprocessor branches stay inert.
use super::{attribute_name, def_name, module_diagnostic, Diagnostic};
use std::collections::{HashMap, HashSet};
use syntax::{SyntaxKind as SK, SyntaxNode, SyntaxToken};

fn tokens(node: &SyntaxNode) -> Vec<SyntaxToken> {
    node.children_with_tokens()
        .filter_map(|e| e.into_token())
        .filter(|t| !t.kind().is_trivia())
        .collect()
}
fn has(node: &SyntaxNode, kind: SK) -> bool {
    node.children_with_tokens().any(|e| e.kind() == kind)
}
fn ty(node: &SyntaxNode) -> Option<SyntaxNode> {
    node.children().find(|n| n.kind().is_type_node())
}
fn normalized(node: &SyntaxNode) -> String {
    node.descendants_with_tokens()
        .filter_map(|e| e.into_token())
        .filter(|t| !t.kind().is_trivia())
        .map(|t| t.text().to_owned())
        .collect()
}
fn error(out: &mut Vec<Diagnostic>, node: &SyntaxNode, message: impl Into<String>) {
    out.push(module_diagnostic("type-error", message.into(), node.text_range()));
}

pub(super) fn check(
    defs: &[SyntaxNode],
    workspace: Option<&crate::WorkspaceNames>,
    scope: Option<&super::OrderedScope<'_>>,
    out: &mut Vec<Diagnostic>,
) {
    // Keep type and value namespaces separate: a function with the same
    // spelling must not hide a synonym needed by declaration checks.
    let named: HashMap<_, _> = defs
        .iter()
        .filter(|n| {
            n.kind() == SK::TYPE_ALIAS_DEF
                || [SK::KW_STRUCT, SK::KW_UNION, SK::KW_ENUM, SK::KW_BITFIELD, SK::KW_NEWTYPE]
                    .into_iter()
                    .any(|kind| has(n, kind))
        })
        .filter_map(|n| def_name(n).map(|(name, _)| (name, n)))
        .collect();
    let specs: HashMap<_, _> = defs
        .iter()
        .filter(|n| n.kind() == SK::CALLABLE_SPEC)
        .filter_map(|n| def_name(n).map(|(name, _)| (name, n)))
        .collect();
    let heads: HashSet<_> = defs
        .iter()
        .filter(|n| n.kind() == SK::SCATTERED_DEF)
        .filter_map(|n| def_name(n).map(|(name, _)| name))
        .collect();
    let mappings: HashSet<_> = defs
        .iter()
        .filter(|d| super::mapping_signature(d).is_some())
        .filter_map(|d| def_name(d).map(|n| n.0))
        .collect();
    let mut order: Option<String> = None;
    for def in defs {
        if def.kind() == SK::DEFAULT_DEF {
            if let Some(t) =
                tokens(def).into_iter().find(|t| matches!(t.kind(), SK::KW_INC | SK::KW_DEC))
            {
                if order.as_ref().is_some_and(|old| old != t.text()) {
                    out.push(module_diagnostic(
                        "type-error",
                        "Cannot change default order once already set".into(),
                        t.text_range(),
                    ));
                }
                order = Some(t.text().into());
            }
        }
        if scope.is_none()
            && def.kind() == SK::SCATTERED_CLAUSE_DEF
            && (has(def, SK::KW_ENUM) || has(def, SK::KW_UNION))
        {
            if let Some((name, range)) = def_name(def) {
                if !heads.contains(&name)
                    && !workspace.is_some_and(|w| w.scattered_heads.contains(&name))
                {
                    let message = if has(def, SK::KW_ENUM) {
                        format!("Enumeration {name} does not exist")
                    } else {
                        format!("{name} has no scattered declaration")
                    };
                    out.push(module_diagnostic("type-error", message, range));
                }
            }
        }
        if def.kind() == SK::CALLABLE_DEF {
            if has(def, SK::KW_IMPL) {
                let range = def_name(def).map_or(def.text_range(), |(_, range)| range);
                out.push(module_diagnostic(
                    "type-error",
                    "Cannot declare an implementation outside of an outcome".into(),
                    range,
                ));
            } else if let Some((name, _)) = def_name(def) {
                // Sail permits explicit implementations of the four
                // signatures generated by a real mapping declaration.
                let generated =
                    ["_forwards_matches", "_backwards_matches", "_forwards", "_backwards"]
                        .iter()
                        .any(|suffix| {
                            name.strip_suffix(suffix).is_some_and(|base| {
                                scope.map_or_else(
                                    || {
                                        mappings.contains(base)
                                            || workspace.is_some_and(|w| {
                                                w.mapping_spec_names.contains(base)
                                            })
                                    },
                                    |scope| {
                                        scope
                                            .node(def, base, super::Namespace::Callable)
                                            .is_some_and(|n| super::mapping_signature(&n).is_some())
                                    },
                                )
                            })
                        });
                let selected =
                    scope.and_then(|scope| scope.node(def, &name, super::Namespace::Callable));
                let declared = generated
                    || scope.map_or_else(
                        || {
                            specs.contains_key(&name)
                                || workspace.is_some_and(|w| w.value_spec_names.contains(&name))
                        },
                        |_| selected.as_ref().is_some_and(|n| n.kind() == SK::CALLABLE_SPEC),
                    );
                if has(def, SK::KW_MAPPING) && !def.children().any(|n| n.kind().is_type_node()) {
                    if !declared {
                        error(out, def, "Mapping does not have any declared type");
                    } else if !scope.map_or_else(
                        || {
                            specs.get(&name).is_some_and(|n| super::mapping_signature(n).is_some())
                                || workspace.is_some_and(|w| w.mapping_spec_names.contains(&name))
                        },
                        |_| {
                            selected.as_ref().is_some_and(|n| super::mapping_signature(n).is_some())
                        },
                    ) {
                        error(out, def, "Mapping type must be a bi-directional mapping");
                    }
                } else if has(def, SK::KW_FUNCTION) && !declared && !has(def, SK::KW_CLAUSE) {
                    if !has(def, SK::R_ARROW) && !def.children().any(|n| n.kind() == SK::TYPE_ARROW)
                    {
                        error(out, def, "Cannot infer function type for unannotated function");
                    } else if let Some(params) = def.children().find(|n| n.kind() == SK::PARAM_LIST)
                    {
                        if !def.children().any(|n| n.kind() == SK::TYPE_ARROW) {
                            if let Some(range) = uninferable_parameter(&params) {
                                out.push(module_diagnostic(
                                    "type-error",
                                    "Cannot infer type from unannotated parameter pattern".into(),
                                    range,
                                ));
                            }
                        }
                    }
                }
            }
        }
        if def.kind() == SK::OUTCOME_DEF {
            for child in def.children().filter(|n| {
                matches!(
                    n.kind(),
                    SK::CALLABLE_DEF
                        | SK::CALLABLE_SPEC
                        | SK::NAMED_DEF
                        | SK::TYPE_ALIAS_DEF
                        | SK::DEFINITION
                        | SK::SCATTERED_DEF
                        | SK::SCATTERED_CLAUSE_DEF
                        | SK::DEFAULT_DEF
                        | SK::OUTCOME_DEF
                        | SK::CONSTRAINT_DEF
                        | SK::INSTANTIATION_DEF
                )
            }) {
                if child.kind() != SK::CALLABLE_SPEC
                    && !(child.kind() == SK::CALLABLE_DEF && has(&child, SK::KW_IMPL))
                {
                    error(out, &child, "Forbidden definition in outcome block");
                }
            }
        }
        for node in def.descendants() {
            if node.kind() == SK::RETURN_EXPR
                && def.kind() != SK::CALLABLE_DEF
                && def.kind() != SK::SCATTERED_CLAUSE_DEF
                && def.kind() != SK::OUTCOME_DEF
            {
                error(out, &node, "Cannot use return outside a function");
            }
            if node.kind() == SK::MAPPING_CLAUSE && has(&node, SK::KW_IF) && has(&node, SK::KW_WHEN)
            {
                let range = node
                    .children_with_tokens()
                    .skip_while(|e| e.kind() != SK::KW_WHEN)
                    .skip(1)
                    .find(|e| !e.kind().is_trivia())
                    .map_or(node.text_range(), |e| e.text_range());
                out.push(module_diagnostic(
                    "type-error",
                    "Mapping clause has both a 'when' guard and an 'if' clause".into(),
                    range,
                ));
            }
            if node.kind() == SK::ATTRIBUTE {
                let name = attribute_name(&node).unwrap_or_default();
                if matches!(name.as_str(), "enum_vector" | "extension") {
                    let ts = tokens(&node);
                    let argument: Vec<_> = ts
                        .iter()
                        .skip_while(|t| t.kind() != SK::IDENT)
                        .skip(1)
                        .take_while(|t| t.kind() != SK::R_BRACK)
                        .collect();
                    if argument.len() != 1
                        || !matches!(argument[0].kind(), SK::STRING_LIT | SK::IDENT)
                    {
                        error(
                            out,
                            &node,
                            format!("Invalid {name} attribute: expected a string argument"),
                        );
                    }
                }
            }
        }
        let types = TypeLookup { legacy: &named, ordered: scope.map(|s| (s.db, s.at(def))) };
        check_types(def, types, out);
        if has(def, SK::KW_BITFIELD) {
            if let Some(base) = ty(def) {
                let base = resolve_alias(base, types, 0).0;
                let head = type_head(&base);
                if matches!(
                    head.as_str(),
                    "int" | "nat" | "bool" | "unit" | "string" | "real" | "vector" | "list"
                ) || base.kind() == SK::TYPE_TUPLE
                {
                    error(
                        out,
                        def,
                        format!(
                            "Underlying bitfield type {} must be a constant-width bitvector",
                            base.text()
                        ),
                    );
                }
            }
        }
    }
}

/// The only patterns upstream can infer a signature from are literals,
/// annotated patterns, and tuples of those (infer_funtyp/typ_from_pat).
fn uninferable_parameter(node: &SyntaxNode) -> Option<syntax::TextRange> {
    let mut groups: Vec<Vec<syntax::SyntaxElement>> = vec![Vec::new()];
    for el in node.children_with_tokens().filter(|e| !e.kind().is_trivia()) {
        if matches!(el.kind(), SK::L_PAREN | SK::R_PAREN) {
            continue;
        }
        if el.kind() == SK::COMMA {
            groups.push(Vec::new());
        } else {
            groups.last_mut().unwrap().push(el);
        }
    }
    groups
        .iter()
        .find(|group| {
            !(group.iter().any(|e| e.kind() == SK::COLON || e.kind() == SK::TYPED_PAT)
                || group.iter().all(|e| {
                    matches!(
                        e.kind(),
                        SK::NUM_LIT
                            | SK::BIN_LIT
                            | SK::HEX_LIT
                            | SK::STRING_LIT
                            | SK::UNIT
                            | SK::KW_TRUE
                            | SK::KW_FALSE
                            | SK::LITERAL_PAT
                    )
                }))
        })
        .and_then(|group| group.first().map(|e| e.text_range()))
}

fn type_head(node: &SyntaxNode) -> String {
    if node.kind() == SK::TYPE_APP {
        node.first_child().map_or(String::new(), |n| normalized(&n))
    } else {
        normalized(node)
    }
}
/// Following an alias also follows the environment in which its RHS was
/// declared. Public aliases may expose private support types without making
/// those names available at the use site.
#[derive(Clone, Copy)]
struct TypeLookup<'a> {
    legacy: &'a HashMap<String, &'a SyntaxNode>,
    ordered: Option<(&'a dyn salsa::Database, Option<hir::source_order::Declaration>)>,
}
impl<'a> TypeLookup<'a> {
    fn get(self, name: &str) -> Option<(SyntaxNode, Self)> {
        if let Some((db, at)) = self.ordered {
            let declaration = hir::source_order::bindings::resolve_before(
                db,
                at?,
                hir::Name::new(name),
                super::Namespace::Type,
            )?;
            let node = hir::source_order::node(db, declaration)?;
            Some((node, Self { ordered: Some((db, Some(declaration))), ..self }))
        } else {
            Some(((*self.legacy.get(name)?).clone(), self))
        }
    }
}
fn resolve_alias<'a>(
    mut node: SyntaxNode,
    mut defs: TypeLookup<'a>,
    depth: usize,
) -> (SyntaxNode, TypeLookup<'a>) {
    for _ in depth..32 {
        if node.kind() != SK::TYPE_NAMED {
            break;
        }
        let Some((def, env)) =
            defs.get(&normalized(&node)).filter(|(d, _)| d.kind() == SK::TYPE_ALIAS_DEF)
        else {
            break;
        };
        let Some(next) = ty(&def) else { break };
        node = next;
        defs = env;
    }
    (node, defs)
}
fn check_types(def: &SyntaxNode, defs: TypeLookup<'_>, out: &mut Vec<Diagnostic>) {
    for node in def.descendants() {
        if node.kind() == SK::TYPE_EXISTENTIAL
            && node.children().any(|n| n.kind() == SK::TYPE_PARAM_LIST)
            && node.ancestors().skip(1).any(|p| {
                p.kind() == SK::TYPE_EXISTENTIAL
                    && p.children().any(|n| n.kind() == SK::TYPE_PARAM_LIST)
            })
        {
            error(out, &node, "Nested existentials are not allowed");
        }
        if node.kind() == SK::TYPE_NAMED && normalized(&node) == "_" {
            // `_` in a type-pattern is a binder wildcard; annotations need an actual type.
            if !node.ancestors().any(|p| p.kind() == SK::AS_PAT) {
                error(out, &node, "Wildcard type is not allowed here");
            }
        }
        if node.kind() == SK::TYPE_ARROW && has(&node, SK::DOUBLE_ARROW) {
            let sides: Vec<_> = node.children().filter(|n| n.kind().is_type_node()).collect();
            if sides.len() == 2
                && normalized(&resolve_alias(sides[0].clone(), defs, 0).0)
                    == normalized(&resolve_alias(sides[1].clone(), defs, 0).0)
            {
                error(out, &node, "Bidirectional types cannot be the same on both sides");
            }
        }
        if node.kind() == SK::TYPE_APP && has(&node, SK::L_PAREN) {
            let name = type_head(&node);
            if let Some((alias, _)) =
                defs.get(&name).filter(|(d, _)| d.kind() == SK::TYPE_ALIAS_DEF)
            {
                let ts = tokens(&alias);
                let kind = ts.iter().skip_while(|t| t.kind() != SK::COLON).nth(1).map(|t| t.kind());
                if matches!(kind, Some(SK::KW_INT | SK::KW_BOOL))
                    && !alias.children().any(|n| n.kind() == SK::TYPE_PARAM_LIST)
                    && !has(&alias, SK::L_PAREN)
                {
                    let argc = node.children().count().saturating_sub(1);
                    if argc > 0 {
                        error(out, &node, format!("{name} expected 0 arguments, given {argc}"));
                    }
                }
            }
        }
    }
}
